// Command generate-compat emits the frozen compatibility model surface.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"unicode"
)

type Type struct {
	Name     string `json:"name"`
	Args     []Type `json:"arguments,omitempty"`
	External bool   `json:"external,omitempty"`
}
type Field struct {
	Name, Key        string
	Type             Type
	Default, Flatten bool
	Aliases          []string
	Custom           string
}
type Definition struct {
	Kind     string
	Fields   []Field
	Variants []Type
	Type     Type
}

func exported(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == ' ' || r == ':' })
	for i, p := range parts {
		if p == "id" {
			parts[i] = "ID"
		} else if p == "url" {
			parts[i] = "URL"
		} else if p != "" {
			r := []rune(p)
			r[0] = unicode.ToUpper(r[0])
			parts[i] = string(r)
		}
	}
	return strings.Join(parts, "")
}
func goType(t Type) string {
	switch t.Name {
	case "optional", "box":
		return "*" + goType(t.Args[0])
	case "array":
		return "[]" + goType(t.Args[0])
	case "map":
		return "map[string]" + goType(t.Args[1])
	case "raw":
		return "json.RawMessage"
	case "exact_number":
		return "json.Number"
	case "null":
		return "Null"
	}
	if t.External {
		return "models." + t.Name
	}
	return t.Name
}
func variantName(t Type) string {
	if t.Name == "exact_number" {
		return "Number"
	}
	if t.Name == "array" {
		return "Array"
	}
	if t.Name == "map" {
		return "Object"
	}
	if t.Name == "optional" {
		return "Optional" + variantName(t.Args[0])
	}
	if t.Name == "box" {
		return variantName(t.Args[0])
	}
	return exported(t.Name)
}
func main() {
	check := flag.Bool("check", false, "check committed generation without writing")
	flag.Parse()
	metadata := map[string]Definition{}
	metadataBytes, e := os.ReadFile("spec/compatibility-models.json")
	must(e)
	must(json.Unmarshal(metadataBytes, &metadata))
	names := []string{}
	for n := range metadata {
		names = append(names, n)
	}
	sort.Strings(names)
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./cmd/generate-compat; DO NOT EDIT.\npackage compat\n\nimport (\"encoding/json\";\"fmt\";\"github.com/swervelord/Torn-Go-SDK/models\")\nvar _ = fmt.Errorf\n")
	for _, name := range names {
		d := metadata[name]
		switch d.Kind {
		case "alias":
			fmt.Fprintf(&out, "type %s = %s\n", name, goType(d.Type))
		case "struct":
			fmt.Fprintf(&out, "type %s struct {\n", name)
			for _, f := range d.Fields {
				tag := f.Key
				if f.Flatten {
					tag = "-"
				}
				fmt.Fprintf(&out, "%s %s `json:%q`\n", exported(f.Name), goType(f.Type), tag)
			}
			out.WriteString("}\n")
			fmt.Fprintf(&out, "func(v *%s) UnmarshalJSON(data []byte) error { type plain %s; var n plain; if err:=decodeStruct(data,&n,[]fieldRule{", name, name)
			for _, f := range d.Fields {
				fmt.Fprintf(&out, "{Name:%q,Key:%q,Default:%t,Optional:%t,Flatten:%t,Aliases:[]string{", exported(f.Name), f.Key, f.Default, f.Type.Name == "optional", f.Flatten)
				for _, a := range f.Aliases {
					fmt.Fprintf(&out, "%q,", a)
				}
				fmt.Fprintf(&out, "},Custom:%q},", f.Custom)
			}
			fmt.Fprintf(&out, "});err!=nil{return fmt.Errorf(%q,err)};*v=%s(n);return nil}\n", name+": %w", name)
			fmt.Fprintf(&out, "func(v %s) MarshalJSON()([]byte,error){type plain %s;return encodeStruct(plain(v))}\n", name, name)
		case "union":
			fmt.Fprintf(&out, "type %s struct {\n", name)
			for _, v := range d.Variants {
				fmt.Fprintf(&out, "%s *%s `json:\"-\"`\n", variantName(v), goType(v))
			}
			out.WriteString("}\n")
			fmt.Fprintf(&out, "func(v *%s) UnmarshalJSON(data []byte)error{*v=%s{};", name, name)
			if special := specialBody(name, d); special != "" {
				out.WriteString(special)
			} else {
				for _, v := range d.Variants {
					fmt.Fprintf(&out, "{var x %s;if err:=decodeVariant(data,&x,%t);err==nil {v.%s=&x;return nil}};", goType(v), v.Name == "optional" || v.Name == "null" || v.Name == "raw", variantName(v))
				}
				fmt.Fprintf(&out, "return fmt.Errorf(%q)", "no compatible "+name+" variant")
			}
			out.WriteString("}\n")
			fmt.Fprintf(&out, "func(v %s) MarshalJSON()([]byte,error){", name)
			for _, v := range d.Variants {
				fmt.Fprintf(&out, "if v.%s!=nil{return json.Marshal(v.%s)};", variantName(v), variantName(v))
			}
			out.WriteString("return []byte(\"null\"),nil}\n")
			for _, v := range d.Variants {
				fmt.Fprintf(&out, "func(v %s) As%s()(%s,bool){if v.%s!=nil{return *v.%s,true};var zero %s;return zero,false}\n", name, variantName(v), goType(v), variantName(v), variantName(v), goType(v))
			}
		}
	}
	out.WriteString("func(v CompanyProfileBundle) Profile() CompanyProfile{return v.Company}\nfunc(v UserReportDetails) Get(key string)(DynamicValue,bool){x,ok:=v.Fields[key];return x,ok}\nfunc(v UserPersonalStatsBucket) Get(key string)(DynamicValue,bool){x,ok:=v.Stats[key];return x,ok}\n")
	b, e := format.Source(out.Bytes())
	if e != nil {
		os.WriteFile("compat/broken.txt", out.Bytes(), 0644)
		panic(e)
	}
	if *check {
		existing, e := os.ReadFile("compat/models_generated.go")
		must(e)
		if !bytes.Equal(existing, b) {
			panic("compatibility generation is stale")
		}
	} else {
		must(os.WriteFile("compat/models_generated.go", b, 0644))
	}
	declarations := []map[string]any{}
	dynamic := []string{}
	customFields := []string{}
	var scanType func(Type, string)
	scanType = func(t Type, path string) {
		if t.Name == "raw" {
			dynamic = append(dynamic, path)
		}
		for _, a := range t.Args {
			scanType(a, path)
		}
	}
	for _, name := range names {
		d := metadata[name]
		fields := []map[string]any{}
		for _, f := range d.Fields {
			fields = append(fields, map[string]any{"wire_name": f.Key, "public_field": exported(f.Name), "go_type": goType(f.Type), "aliases": f.Aliases, "default": f.Default, "flatten": f.Flatten, "custom_decoder": f.Custom})
			scanType(f.Type, name+"."+f.Name)
			if f.Custom != "" {
				customFields = append(customFields, name+"."+f.Name)
			}
		}
		if d.Kind == "alias" {
			scanType(d.Type, name)
		}
		for _, v := range d.Variants {
			scanType(v, name)
		}
		declarations = append(declarations, map[string]any{"name": name, "kind": d.Kind, "public_api": "compat." + name, "fields": fields})
	}
	digest := sha256.Sum256(metadataBytes)
	report := map[string]any{"metadata": "spec/compatibility-models.json", "sha256": fmt.Sprintf("%x", digest), "declaration_count": len(names), "declarations": declarations, "unconstrained_json_paths": dynamic, "custom_decoder_fields": customFields, "historical_evidence": "Maintained compatibility contract; not an independently authenticated historical OpenAPI specification.", "dynamic_number_policy": "Signed int64 when representable; otherwise exact json.Number. Unknown JSON is never converted through float64."}
	reportBytes, e := json.MarshalIndent(report, "", "  ")
	must(e)
	reportBytes = append(reportBytes, '\n')
	if *check {
		existing, e := os.ReadFile("spec/compatibility-typing-report.json")
		must(e)
		if !bytes.Equal(existing, reportBytes) {
			panic("compatibility typing report is stale")
		}
	} else {
		must(os.WriteFile("spec/compatibility-typing-report.json", reportBytes, 0644))
	}
	fmt.Printf("generated %d compatibility model declarations\n", len(names))
}
func must(e error) {
	if e != nil {
		panic(e)
	}
}
func specialBody(name string, d Definition) string {
	switch name {
	case "TradeItem", "UserEmployment", "UserCompetition", "UserOrganizedCrimeSelection", "FactionWarfareEntry":
		return "if err:=decodeSpecial(" + fmt.Sprintf("%q", name) + ",data,v);err==nil{return nil}else{return err};"
	}
	return ""
}
