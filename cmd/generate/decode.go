package main

import (
	"bytes"
	"fmt"
)

func emitDecoders(g *generator, check bool) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./cmd/generate; DO NOT EDIT.\npackage %s\nimport(\"encoding/json\";\"fmt\")\n// DecodeSchema dynamically chooses a concrete component type. Prefer direct typed decoding when the schema is known statically.\nfunc DecodeSchema(name string,data []byte)(any,error){var out any;switch name{\n", g.pkg)
	for _, n := range keys(g.schemas) {
		fmt.Fprintf(&b, "case %q:out=new(%s)\n", n, name(n))
	}
	b.WriteString("default:return nil,fmt.Errorf(\"unknown component schema %s\",name)};if err:=json.Unmarshal(data,out);err!=nil{return nil,err};return out,nil}\n")
	write(g.pkg+"/decode_generated.go", b.Bytes(), check)
}
