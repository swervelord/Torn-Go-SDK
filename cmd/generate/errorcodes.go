package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
)

// errorCodes generates errorcodes_generated.go from spec/shared/error-codes.json
// (PARITY_SPEC P5.1, P2.3, P4.1, P4.2): the ErrorCode enum, its policy table and
// the retry defaults.
func errorCodes(check bool) {
	var doc struct {
		SpecVersion string `json:"spec_version"`
		Retry       struct {
			MaxAttempts     int    `json:"max_attempts"`
			BaseDelayMS     int    `json:"base_delay_ms"`
			MaxDelayMS      int    `json:"max_delay_ms"`
			Jitter          string `json:"jitter"`
			RetryAfterCapMS int    `json:"retry_after_cap_ms"`
			HTTPRetryStatus []int  `json:"http_retry_statuses"`
			NetworkErrors   string `json:"network_errors"`
		} `json:"retry"`
		Codes []struct {
			Code       int    `json:"code"`
			Schema     string `json:"schema"`
			Name       string `json:"name"`
			Snake      string `json:"snake"`
			Message    string `json:"message"`
			Category   string `json:"category"`
			Action     string `json:"action"`
			DisableKey string `json:"disable_key"`
			Retryable  bool   `json:"retryable"`
		} `json:"codes"`
	}
	raw, err := os.ReadFile("spec/shared/error-codes.json")
	if err != nil {
		panic(err)
	}
	if err = json.Unmarshal(raw, &doc); err != nil {
		panic(err)
	}
	if doc.Retry.Jitter != "full" || doc.Retry.NetworkErrors != "retry_backoff" {
		panic("unsupported retry policy in spec/shared/error-codes.json")
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by go run ./cmd/generate from spec/shared/error-codes.json; DO NOT EDIT.\npackage torn\nimport \"time\"")
	fmt.Fprintf(&b, "// Retry defaults shared by every Torn SDK (spec/shared/error-codes.json, P4.2).\nconst(\n// DefaultMaxAttempts counts total sends of one request.\nDefaultMaxAttempts=%d\n// DefaultRetryBaseDelay is the first backoff delay; later delays double.\nDefaultRetryBaseDelay=%d*time.Millisecond\n// DefaultRetryMaxDelay caps exponential backoff.\nDefaultRetryMaxDelay=%d*time.Millisecond\n// DefaultRetryAfterCap caps a server Retry-After delay.\nDefaultRetryAfterCap=%d*time.Millisecond\n)\n", doc.Retry.MaxAttempts, doc.Retry.BaseDelayMS, doc.Retry.MaxDelayMS, doc.Retry.RetryAfterCapMS)
	fmt.Fprint(&b, "// retryHTTPStatuses are HTTP statuses retried with backoff.\nvar retryHTTPStatuses=map[int]bool{")
	for _, s := range doc.Retry.HTTPRetryStatus {
		fmt.Fprintf(&b, "%d:true,", s)
	}
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b, "// Torn API error codes (P5.1). Unknown codes are representable: ErrorCode(n).IsKnown() is false.\nconst(")
	for _, c := range doc.Codes {
		fmt.Fprintf(&b, "// Code%s is Torn error %d: %s\nCode%s ErrorCode=%d\n", c.Name, c.Code, c.Message, c.Name, c.Code)
	}
	fmt.Fprintln(&b, ")\nvar errorCodeTable=map[ErrorCode]errorCodeInfo{")
	for _, c := range doc.Codes {
		fmt.Fprintf(&b, "Code%s:{name:%q,snake:%q,schema:%q,message:%q,category:%q,action:%q,disableKey:%q,retryable:%t},\n", c.Name, c.Name, c.Snake, c.Schema, c.Message, c.Category, c.Action, c.DisableKey, c.Retryable)
	}
	fmt.Fprintln(&b, "}")
	fmt.Fprint(&b, "// ErrorCodes returns every known Torn error code in ascending order.\nfunc ErrorCodes()[]ErrorCode{return []ErrorCode{")
	for _, c := range doc.Codes {
		fmt.Fprintf(&b, "Code%s,", c.Name)
	}
	fmt.Fprintln(&b, "}}")
	fmt.Fprintf(&b, "const errorCodesSpecVersion=%q\n", doc.SpecVersion)
	write("errorcodes_generated.go", b.Bytes(), check)
}
