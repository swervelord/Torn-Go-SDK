func operations(spec S, g *generator, check bool) {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by go run ./cmd/generate; DO NOT EDIT.\npackage torn\nimport(\"context\";\"encoding/json\";\"fmt\";\"github.com/swervelord/Torn-Go-SDK/models\")\nvar _=models.Validate")
	type entry struct {
		ID              string `json:"operationId"`
		Path            string `json:"path"`
		Method          string `json:"method"`
		Params          string `json:"params"`
		Response        string `json:"response"`
		CSV             bool   `json:"csv"`
		Stability       string `json:"stability"`
		CacheTTLSeconds int    `json:"cacheTTLSeconds,omitempty"`
	}
	entries := []entry{}
	paths := obj(spec["paths"])
	g.prefix = "models."
	for _, path := range keys(paths) {
		pathitem := obj(paths[path])
		for _, method := range keys(pathitem) {
			op := obj(pathitem[method])
			id := str(op["operationId"])
			if id == "" {
				continue
			}
			n := name(id)
			params := []any{}
			if a, ok := pathitem["parameters"].([]any); ok {
				params = append(params, a...)
			}
			if a, ok := op["parameters"].([]any); ok {
				params = append(params, a...)
			}
			required := []any{}
			properties := S{}
			fmt.Fprintf(&b, "// %sParams contains documented parameters for %s %s.\ntype %sParams struct{\n", n, strings.ToUpper(method), path, n)
			seen := map[string]bool{}
			for _, p := range params {
				m := obj(p)
				if ref := str(m["$ref"]); ref != "" {
					m = obj(obj(obj(spec["components"])["parameters"])[strings.TrimPrefix(ref, "#/components/parameters/")])
				}
				key := str(m["name"])
				if seen[key] {
					continue
				}
				seen[key] = true
				s := obj(m["schema"])
				properties[key] = s
				t := g.typ(s, n+"Param"+name(key))
				if m["required"] == true {
					required = append(required, key)
				} else {
					t = "*" + t
				}
				tag := key
				if m["required"] != true {
					tag += ",omitempty"
				}
				extra := ""
				if m["in"] == "path" {
					extra = " path:" + fmt.Sprintf("%q", key)
				}
				fmt.Fprintf(&b, "%s %s `json:%q%s`\n", name(key), t, tag, extra)
			}
			fmt.Fprintln(&b, "}")
			responses := obj(op["responses"])
			response := obj(responses["200"])
			content := obj(response["content"])
			csv := content["text/csv"] != nil
			media := obj(content["application/json"])
			if csv {
				media = obj(content["text/csv"])
			}
			schema := obj(media["schema"])
			t := g.typ(schema, n+"ResponseBody")
			fmt.Fprintf(&b, "type %sResponse = %s\n", n, t)
			raw, _ := json.Marshal(S{"type": "object", "required": required, "properties": properties})
			fmt.Fprintf(&b, "// %s executes operation %s using its exact documented path.\nfunc(c *Client)%s(ctx context.Context,params %sParams,opts ...RequestOptions)(%sResponse,ExecutionReport,error){var out %sResponse;var report ExecutionReport;if len(opts)>1{return out,report,fmt.Errorf(\"at most one RequestOptions is allowed\")};var options RequestOptions;if len(opts)==1{options=opts[0]};encoded,err:=json.Marshal(params);if err!=nil{return out,report,err};if err=models.ValidateSchema([]byte(%q),encoded);err!=nil{return out,report,fmt.Errorf(%q,err)};raw,report,err:=c.DoOperation(ctx,Operation{ID:%q,Path:%q,Method:%q,CSV:%t},params,options);if err!=nil{return out,report,err};if err=json.Unmarshal(raw,&out);err!=nil{return out,report,err};return out,report,nil}\n", n, id, n, n, n, n, string(raw), id+" parameters: %w", id, path, strings.ToUpper(method), csv)
			ttl := 0
			switch path {
			case "/user/inventory":
				ttl = 900
			case "/faction/inventory":
				ttl = 300
			}
			entries = append(entries, entry{id, path, strings.ToUpper(method), n + "Params", n + "Response", csv, str(op["x-stability"]), ttl})
		}
	}
	fmt.Fprintln(&b, "// Operations lists the complete pinned exact-operation inventory.\nvar Operations = []Operation{")
	for _, e := range entries {
		fmt.Fprintf(&b, "{ID:%q,Path:%q,Method:%q,CSV:%t},\n", e.ID, e.Path, e.Method, e.CSV)
	}
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b, "var operationMetadata = map[string]OperationMetadata{")
	for _, e := range entries {
		fmt.Fprintf(&b, "%q:{Stability:%q,CacheTTLSeconds:%d},\n", e.ID, e.Stability, e.CacheTTLSeconds)
	}
	fmt.Fprintln(&b, "}")
	write("operations_generated.go", b.Bytes(), check)
	manifest := S{"version": "6.14.0", "operationCount": len(entries), "componentSchemaCount": len(g.schemas), "operations": entries, "schemas": S{}}
	for _, n := range keys(g.schemas) {
		obj(manifest["schemas"])[n] = "models." + name(n)
	}
	raw, _ := json.MarshalIndent(manifest, "", "  ")
	write("spec/model-coverage.json", append(raw, '\n'), check)
	g.prefix = ""
	emitModels(g, check)
}
func emitModels(g *generator, check bool) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./cmd/generate; DO NOT EDIT.\npackage %s\nimport(\"encoding/json\";\"github.com/swervelord/Torn-Go-SDK/internal/contract\")\nvar _ = contract.Schema{}\n", g.pkg)
	for i := 0; i < len(g.order); i++ {
		g.emit(g.order[i], &b)
	}
	write(g.pkg+"/types_generated.go", b.Bytes(), check)
	raw, _ := json.Marshal(g.definitions)
	write(g.pkg+"/schemas_generated.json", raw, check)
}
