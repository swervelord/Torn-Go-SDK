// sharedAccessLevels reads spec/shared/access-levels.json (PARITY_SPEC P6.1),
// the access-level source shared by every Torn SDK.
func sharedAccessLevels(version string) map[string]string {
	var doc struct {
		SpecVersion string `json:"spec_version"`
		Operations  map[string]struct {
			Path   string `json:"path"`
			Access string `json:"access"`
		} `json:"operations"`
	}
	raw, err := os.ReadFile("spec/shared/access-levels.json")
	if err != nil {
		panic(err)
	}
	if err = json.Unmarshal(raw, &doc); err != nil {
		panic(err)
	}
	if doc.SpecVersion != version {
		panic("spec/shared/access-levels.json is for " + doc.SpecVersion + ", not " + version)
	}
	out := map[string]string{}
	for id, op := range doc.Operations {
		out[id] = op.Access
	}
	return out
}

func operations(spec S, g *generator, check bool) {
	const version = "6.15.0"
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by go run ./cmd/generate; DO NOT EDIT.\npackage torn\nimport(\"context\";\"encoding/json\";\"iter\";\"sync\";\"github.com/swervelord/Torn-Go-SDK/models\")\nvar _=models.Validate\nvar _ iter.Seq[int]")
	type entry struct {
		ID              string `json:"operationId"`
		Path            string `json:"path"`
		Method          string `json:"method"`
		Params          string `json:"params"`
		Response        string `json:"response"`
		CSV             bool   `json:"csv"`
		Stability       string `json:"stability"`
		CacheTTLSeconds int    `json:"cacheTTLSeconds,omitempty"`
		AccessLevel     string `json:"accessLevel"`
		Paginated       bool   `json:"paginated,omitempty"`
		schema          string
	}
	access := sharedAccessLevels(version)
	entries := []entry{}
	paths := obj(spec["paths"])
	g.prefix = "models."
	for _, path := range keys(paths) {
		pathitem := obj(paths[path])
		for _, method := range keys(pathitem) {
			op := obj(pathitem[method])
			id := str(op["operationId"])
			if id == "" {
				continue
			}
			n := name(id)
			params := []any{}
			if a, ok := pathitem["parameters"].([]any); ok {
				params = append(params, a...)
			}
			if a, ok := op["parameters"].([]any); ok {
				params = append(params, a...)
			}
			required := []any{}
			properties := S{}
			fmt.Fprintf(&b, "// %sParams contains documented parameters for %s %s.\ntype %sParams struct{\n", n, strings.ToUpper(method), path, n)
			seen := map[string]bool{}
			keyComponent := ""
			for _, p := range params {
				m := obj(p)
				if ref := str(m["$ref"]); ref != "" {
					component := strings.TrimPrefix(ref, "#/components/parameters/")
					if strings.HasPrefix(component, "ApiKey") {
						keyComponent = strings.ToLower(strings.TrimPrefix(component, "ApiKey"))
					}
					m = obj(obj(obj(spec["components"])["parameters"])[component])
				}
				key := str(m["name"])
				if seen[key] {
					continue
				}
				seen[key] = true
				s := obj(m["schema"])
				properties[key] = s
				t := g.typ(s, n+"Param"+name(key))
				if m["required"] == true {
					required = append(required, key)
				} else {
					t = "*" + t
				}
				tag := key
				if m["required"] != true {
					tag += ",omitempty"
				}
				extra := ""
				if m["in"] == "path" {
					extra = " path:" + fmt.Sprintf("%q", key)
				}
				if key == "key" {
					fmt.Fprintln(&b, "// Deprecated: configure keys on the Client. A key set here is sent for this\n// request in the Authorization header, never in the URL (PARITY_SPEC P2.1).")
				} else if d := strings.TrimSpace(str(m["description"])); d != "" {
					fmt.Fprintf(&b, "// %s is the %s parameter %q.\n", name(key), str(m["in"]), key)
				}
				fmt.Fprintf(&b, "%s %s `json:%q%s`\n", name(key), t, tag, extra)
			}
			fmt.Fprintln(&b, "}")
			level, ok := access[id]
			if !ok {
				panic("spec/shared/access-levels.json lacks " + id)
			}
			if keyComponent != "" && keyComponent != level {
				panic(fmt.Sprintf("%s: access level %s in spec/shared/access-levels.json, %s in the OpenAPI key parameter", id, level, keyComponent))
			}
			responses := obj(op["responses"])
			response := obj(responses["200"])
			content := obj(response["content"])
			csv := content["text/csv"] != nil
			media := obj(content["application/json"])
			if csv {
				media = obj(content["text/csv"])
			}
			schema := obj(media["schema"])
			t := g.typ(schema, n+"ResponseBody")
			schemaName := ""
			if strings.HasPrefix(t, "models.") {
				schemaName = strings.TrimPrefix(t, "models.")
			}
			fmt.Fprintf(&b, "// %sResponse is the decoded 200 response of %s.\ntype %sResponse = %s\n", n, id, n, t)
			raw, _ := json.Marshal(S{"type": "object", "required": required, "properties": properties})
			fmt.Fprintf(&b, "var %sParamsSchema=sync.OnceValue(func()models.CompiledSchema{return models.CompileSchema(%q)})\n", lower(n), string(raw))
			fmt.Fprintf(&b, "// %s executes operation %s (%s %s; key access: %s) using its exact documented path.\nfunc(c *Client)%s(ctx context.Context,params %sParams,opts ...RequestOptions)(%sResponse,ExecutionReport,error){var out %sResponse;options,err:=singleOptions(opts);if err!=nil{return out,ExecutionReport{},err};encoded,err:=json.Marshal(params);if err!=nil{return out,ExecutionReport{},err};if err=%sParamsSchema().ValidateParams(encoded);err!=nil{return out,ExecutionReport{},paramsError(%q,err)};raw,report,err:=c.DoOperation(ctx,Operation{ID:%q,Path:%q,Method:%q,CSV:%t},params,options);if err!=nil{return out,report,err};err=c.decodeResponse(%q,%q,raw,&out,options);return out,report,err}\n", n, id, strings.ToUpper(method), path, level, n, n, n, n, lower(n), id, id, path, strings.ToUpper(method), csv, id, schemaName)
			ttl := 0
			switch path {
			case "/user/inventory":
				ttl = 900
			case "/faction/inventory":
				ttl = 300
			case "/user/newmessages":
				ttl = 3600
			}
			paginated := false
			if !csv && schemaName != "" {
				resp := g.flatten(obj(schema), map[string]bool{})
				props := obj(resp["properties"])
				if md := obj(props["_metadata"]); strings.HasPrefix(str(md["$ref"]), "#/components/schemas/RequestMetadataWithLinks") {
					paginated = true
					fmt.Fprintf(&b, "// %sPager pages through %s by following _metadata.links (P7.1).\nfunc(c *Client)%sPager(params %sParams,opts ...PageOptions)*Pager[%sResponse]{return newOperationPager[%sResponse](c,Operation{ID:%q,Path:%q,Method:\"GET\"},params,%q,opts)}\n", n, id, n, n, n, n, id, path, schemaName)
					var lists []string
					for _, k := range keys(props) {
						p := obj(props[k])
						if p["type"] == "array" {
							lists = append(lists, k)
						}
					}
					if len(lists) == 1 {
						k := lists[0]
						itemType := strings.TrimPrefix(g.typ(obj(props[k]), schemaName+name(k)), "[]")
						field := name(k)
						isRequired := false
						reqs, _ := resp["required"].([]any)
						for _, r := range reqs {
							if r == k {
								isRequired = true
							}
						}
						if !isRequired {
							field += ".Value"
						}
						fmt.Fprintf(&b, "// %sItems iterates the %q items of every %s page (P7.1). Stop early by breaking out of the loop.\nfunc(c *Client)%sItems(ctx context.Context,params %sParams,opts ...PageOptions)iter.Seq2[%s,error]{return Items(ctx,c.%sPager(params,opts...),func(page %sResponse)[]%s{return page.%s})}\n", n, k, id, n, n, itemType, n, n, itemType, field)
					}
				}
			}
			entries = append(entries, entry{id, path, strings.ToUpper(method), n + "Params", n + "Response", csv, str(op["x-stability"]), ttl, level, paginated, schemaName})
		}
	}
	fmt.Fprintln(&b, "// Operations lists the complete pinned exact-operation inventory.\nvar Operations = []Operation{")
	for _, e := range entries {
		fmt.Fprintf(&b, "{ID:%q,Path:%q,Method:%q,CSV:%t},\n", e.ID, e.Path, e.Method, e.CSV)
	}
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b, "var operationMetadata = map[string]OperationMetadata{")
	for _, e := range entries {
		fmt.Fprintf(&b, "%q:{Stability:%q,CacheTTLSeconds:%d,AccessLevel:%q,Paginated:%t,ResponseSchema:%q,Path:%q},\n", e.ID, e.Stability, e.CacheTTLSeconds, e.AccessLevel, e.Paginated, e.schema, e.Path)
	}
	fmt.Fprintln(&b, "}")
	specBytes, err := os.ReadFile("spec/openapi-" + version + ".json")
	if err != nil {
		panic(err)
	}
	fmt.Fprintf(&b, "// SpecSHA256 is the SHA-256 of the pinned OpenAPI document spec/openapi-%s.json (P8.7).\nconst SpecSHA256=%q\n", version, fmt.Sprintf("%x", sha256.Sum256(specBytes)))
	fmt.Fprintln(&b, "var operationDecoders = map[string]func([]byte)(any,error){")
	for _, e := range entries {
		fmt.Fprintf(&b, "%q:func(raw []byte)(any,error){var out %s;err:=decodeModel(raw,&out);return &out,err},\n", e.ID, e.Response)
	}
	fmt.Fprintln(&b, "}")
	write("operations_generated.go", b.Bytes(), check)
	manifest := S{"version": version, "operationCount": len(entries), "componentSchemaCount": len(g.schemas), "operations": entries, "schemas": S{}}
	for _, n := range keys(g.schemas) {
		obj(manifest["schemas"])[n] = "models." + name(n)
	}
	raw, _ := json.MarshalIndent(manifest, "", "  ")
	write("spec/model-coverage.json", append(raw, '\n'), check)
	g.prefix = ""
	emitModels(g, check)
}
func emitModels(g *generator, check bool) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./cmd/generate; DO NOT EDIT.\npackage %s\nimport(\"encoding/json\";\"github.com/swervelord/Torn-Go-SDK/internal/contract\")\nvar _ = contract.Schema{}\n", g.pkg)
	for i := 0; i < len(g.order); i++ {
		g.emit(g.order[i], &b)
	}
	write(g.pkg+"/types_generated.go", b.Bytes(), check)
	raw, _ := json.Marshal(g.definitions)
	write(g.pkg+"/schemas_generated.json", raw, check)
}
